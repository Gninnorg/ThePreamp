"""Generate the 4-bit grey scale (anti-aliased) logo for the SH1122 displays from the high resolution artwork.

Usage: python tools\\make_grey_logo.py [--gamma 0.7] [--preview preview.png]
Writes src\\logo_grey.h (4 bits per pixel, high nibble = left pixel, rows padded to whole bytes).
"""
import argparse
from pathlib import Path
from PIL import Image, ImageChops

W, H = 130, 64
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parents[1] / "Hardware" / "ThePreAmp.png"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gamma", type=float, default=0.7, help="<1 makes thin strokes brighter")
    ap.add_argument("--preview")
    args = ap.parse_args()

    src = Image.open(SOURCE).convert("L")
    ink = ImageChops.invert(src)
    ink = ink.crop(ink.getbbox())

    scale = min(W / ink.width, H / ink.height)
    size = (max(1, round(ink.width * scale)), max(1, round(ink.height * scale)))
    small = ink.resize(size, Image.BOX if scale < 1 else Image.LANCZOS)

    canvas = Image.new("L", (W, H), 0)
    canvas.paste(small, ((W - size[0]) // 2, (H - size[1]) // 2))

    levels = [min(15, round(15 * (v / 255) ** args.gamma)) for v in canvas.getdata()]

    rows = []
    stride = (W + 1) // 2
    for y in range(H):
        row = levels[y * W:(y + 1) * W] + [0] * (stride * 2 - W)
        rows.append([(row[i] << 4) | row[i + 1] for i in range(0, stride * 2, 2)])

    lines = ["#ifndef LOGO_GREY_H", "#define LOGO_GREY_H", "",
             "// Generated by tools/make_grey_logo.py - do not edit by hand.",
             f"// 'ThePreAmp {W}x{H} grey', 4 bits per pixel, high nibble first, rows padded to whole bytes",
             "const uint8_t thePreAmpLogoGrey[] = {"]
    lines += ["  " + ", ".join(f"0x{b:02x}" for b in r) + "," for r in rows]
    lines += ["};", "", "#endif", ""]
    (ROOT / "src" / "logo_grey.h").write_text("\n".join(lines))

    if args.preview:
        prev = Image.new("L", (W, H))
        prev.putdata([l * 17 for l in levels])
        prev.resize((W * 6, H * 6), Image.NEAREST).save(args.preview)


main()
