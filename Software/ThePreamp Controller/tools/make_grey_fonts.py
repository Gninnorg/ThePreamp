"""Generate the anti-aliased (4-bit grey) fonts used for input names and volume on the SH1122 displays.

The glyphs are rendered from Inconsolata Bold (SIL Open Font License, https://github.com/googlefonts/Inconsolata) at
sizes that match the cap height of the former U8g2 bitmap fonts, and keep the old monospace cell width so
text layout is unchanged.

Usage: python tools\\make_grey_fonts.py path\\to\\Inconsolata-Bold.ttf [--gamma 1.0] [--preview preview.png]
Writes lib\\SH1122\\SH1122_greyfonts.cpp
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ASCII = "".join(chr(c) for c in range(32, 127))

# name, pixel size, monospace advance (px), characters
FONTS = [
    ("inb24", 38, 21, ASCII),
    ("inb42", 65, 35, ASCII),
    ("inb63", 97, 51, " -.0123456789"),
]


def render(ttf, size, advance, chars, gamma):
    font = ImageFont.truetype(ttf, size)
    natural = round(font.getlength("0"))
    shift = (advance - natural) // 2
    glyphs, data = [], bytearray()
    ox, oy = advance, size * 2
    for ch in map(chr, range(ord(chars[0]), ord(chars[-1]) + 1)):
        if ch not in chars:
            glyphs.append((0, 0, 0, 0, 0))   # keeps the table indexable by character code
            continue
        img = Image.new("L", (advance * 3, size * 3), 0)
        ImageDraw.Draw(img).text((ox, oy), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if box is None:
            glyphs.append((0, 0, 0, 0, 0))
            continue
        crop = img.crop(box)
        w, h = crop.size
        glyphs.append((len(data), w, h, box[0] - ox + shift, oy - box[1]))
        px = [min(15, round(15 * (v / 255) ** gamma)) for v in crop.tobytes()]
        stride = (w + 1) // 2
        for y in range(h):
            row = px[y * w:(y + 1) * w] + [0] * (stride * 2 - w)
            data += bytes((row[i] << 4) | row[i + 1] for i in range(0, stride * 2, 2))
    return glyphs, data


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ttf")
    ap.add_argument("--gamma", type=float, default=1.0)
    ap.add_argument("--preview")
    args = ap.parse_args()

    out = ["// Generated by tools/make_grey_fonts.py - do not edit by hand.",
           "// Anti-aliased 4-bit glyphs rendered from Inconsolata Bold (SIL Open Font License 1.1).",
           '#include "SH1122.h"', ""]
    total = 0
    preview = []
    for name, size, advance, chars in FONTS:
        glyphs, data = render(args.ttf, size, advance, chars, args.gamma)
        total += len(data)
        out.append(f"static const uint8_t {name}_bitmap[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out += ["};", "", f"static const SH1122GreyGlyph {name}_glyphs[] = {{"]
        out += [f"  {{{o}, {w}, {h}, {x}, {t}}}," for o, w, h, x, t in glyphs]
        out += ["};", ""]
        out += [f"const SH1122GreyFont SH1122_FONT_{name.upper()} = {{{ord(chars[0])}, {ord(chars[-1])}, {advance}, {name}_glyphs, {name}_bitmap}};", ""]
        preview.append((name, size, advance, chars))
        print(f"{name}: {len(chars)} glyphs, {len(data)} bytes")
    print("total bitmap bytes:", total)
    (ROOT / "lib" / "SH1122" / "SH1122_greyfonts.cpp").write_text("\n".join(out))

    if args.preview:
        sheet = Image.new("L", (1100, 330), 0)
        d = ImageDraw.Draw(sheet)
        font = ImageFont.truetype(args.ttf, 65)
        d.text((10, 90), "Input 3 Vol", font=font, fill=255, anchor="ls")
        sheet.save(args.preview)


main()
